#!/usr/bin/env python3
"""Generate the primary manuscript table from complete, seed-paired campaigns.

The actual feasible Pareto size is distinct from the reference-dominating size
stored in historical hypervolume metrics. An all-zero paired endpoint is reported
as uninformative instead of assigning a signed-rank p-value.
"""

import argparse
from collections import Counter
import json
from pathlib import Path

import numpy as np

from mobo_linac.campaigns.analysis import compute_bootstrap_ci
from mobo_linac.io.run_data import read_run_data

ALGORITHMS = ("constrained_qlognehvi", "unconstrained_qlognehvi", "scalarized_bo")


def interval(values):
    estimates = compute_bootstrap_ci(np.asarray(values, dtype=float)[:, None], seed=42)
    return dict(zip(("median", "lower", "upper"), (float(x[0]) for x in estimates)))


def summarize(records):
    groups = {name: sorted((r for r in records if r["algorithm"] == name), key=lambda r: r["seed"])
              for name in ALGORITHMS}
    seeds = [r["seed"] for r in groups[ALGORITHMS[0]]]
    if not seeds or len(seeds) != len(set(seeds)):
        raise ValueError("Require unique paired seeds")
    if any([r["seed"] for r in group] != seeds for group in groups.values()):
        raise ValueError("Require identical paired seeds for all algorithms")
    summary = {}
    for algorithm, group in groups.items():
        summary[algorithm] = {metric: interval([r[metric] for r in group]) for metric in
                              ("feasible_hv", "feasible_percent", "first_feasible", "feasible_pareto_size", "invalid_count", "wall_hours")}
        summary[algorithm]["mean_feasible_percent"] = float(np.mean([r["feasible_percent"] for r in group]))
    pairs = {}
    reference = np.asarray([r["feasible_hv"] for r in groups[ALGORITHMS[0]]])
    for algorithm in ALGORITHMS[1:]:
        delta = reference - np.asarray([r["feasible_hv"] for r in groups[algorithm]])
        pairs[algorithm] = {"difference": interval(delta), "nonzero_pairs": int(np.count_nonzero(delta)),
                            "p_value": None, "test_status": "not_computed"}
        if not np.any(delta):
            pairs[algorithm]["test_status"] = "not_applicable_all_differences_zero"
    return {"bootstrap_resamples": 1000, "bootstrap_seed": 42, "seeds": seeds,
            "algorithms": summary, "paired_hv": pairs, "per_seed": records}


def tex_interval(value):
    return f"{value['median']:,.1f} [{value['lower']:,.1f}, {value['upper']:,.1f}]"


def generate(root, output):
    records = []
    for algorithm in ALGORITHMS:
        for seed in range(42, 52):
            directory = root / "per_seed" / f"{algorithm}_seed_{seed}"
            if not (directory / "run_complete.json").exists():
                raise ValueError(f"Incomplete campaign: {directory}")
            run = read_run_data(directory)
            if len(run.results) != 160:
                raise ValueError(f"Expected complete 160-evaluation campaign: {directory}")
            first = next((i for i, r in enumerate(run.results, 1) if r.simulation_valid and r.physically_feasible), None)
            if first is None:
                raise ValueError("First feasibility requires explicit censoring for a campaign with no feasible observation")
            marker = json.loads((directory / "run_complete.json").read_text())
            proposals = json.loads((directory / "proposal_history.json").read_text())
            records.append({"algorithm": algorithm, "seed": seed,
                "feasible_hv": float(run.hypervolume.feasible_hypervolume.iloc[-1]),
                "feasible_percent": 100 * sum(r.simulation_valid and r.physically_feasible for r in run.results) / len(run.results),
                "first_feasible": first, "feasible_pareto_size": len(run.pareto(feasible=True)),
                "invalid_count": sum(not r.simulation_valid for r in run.results),
                "wall_hours": marker["elapsed_wall_time_s"] / 3600,
                "proposal_methods": dict(Counter(r["metadata"]["method"] for r in proposals))})
    data = summarize(records)
    output.mkdir(parents=True, exist_ok=True)
    (output / "primary_results.json").write_text(json.dumps(data, indent=2) + "\n")
    rows = []
    for label, metric in [("Final feasible hypervolume", "feasible_hv"),
                          ("Feasible fraction (\\%)", "feasible_percent"),
                          ("Evaluations to first feasible point", "first_feasible"),
                          ("Feasible Pareto set size", "feasible_pareto_size"),
                          ("Invalid simulations", "invalid_count")]:
        rows.append(label + " & " + " & ".join(tex_interval(data["algorithms"][a][metric]) for a in ALGORITHMS) + r" \\")
    text = r"""% Generated by scripts/generate_primary_paper_table.py; no simulation is rerun.
\begin{table}[htbp]
\centering
\caption{Primary comparison over ten paired runs, 160 simulations per campaign.
Entries are medians with 95\% percentile bootstrap intervals (1,000 resamples with a fixed seed number).
Hypervolumes use the fixed reference and units of $\mu\mathrm{m}^2\,\mathrm{rad}^2\,\mathrm{MeV}$.
Pareto sizes count feasible nondominated observations, including points outside that reference.}
\label{tab:primary}
\resizebox{\textwidth}{!}{%
\begin{tabular}{lccc}
\toprule
 & Constraint-aware qLogNEHVI & Unconstrained qLogNEHVI & Weighted-sum qLogNEI \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}}
\end{table}
"""
    (output / "primary_results_table.tex").write_text(text)
    print(json.dumps({"algorithms": data["algorithms"], "paired_hv": data["paired_hv"]}, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--benchmark-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=Path("docs/paper"))
    args = parser.parse_args()
    generate(args.benchmark_dir, args.output_dir)
